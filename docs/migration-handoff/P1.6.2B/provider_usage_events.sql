CREATE TABLE IF NOT EXISTS public.provider_usage_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(64) NOT NULL,
    model VARCHAR(128) NOT NULL,
    capability VARCHAR(128) NOT NULL,
    functionality VARCHAR(128) NOT NULL,
    agent VARCHAR(128) NOT NULL,
    input_tokens INTEGER NULL,
    output_tokens INTEGER NULL,
    total_tokens INTEGER NULL,
    latency_ms INTEGER NULL,
    estimated_cost NUMERIC(18,8) NOT NULL,
    quality_score NUMERIC(5,2) NOT NULL,
    success BOOLEAN NOT NULL,
    provider_request_id VARCHAR(256) NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_provider_usage_events_provider
    ON public.provider_usage_events (provider);

CREATE INDEX IF NOT EXISTS ix_provider_usage_events_model
    ON public.provider_usage_events (model);

CREATE INDEX IF NOT EXISTS ix_provider_usage_events_capability
    ON public.provider_usage_events (capability);

CREATE INDEX IF NOT EXISTS ix_provider_usage_events_functionality
    ON public.provider_usage_events (functionality);

CREATE INDEX IF NOT EXISTS ix_provider_usage_events_agent
    ON public.provider_usage_events (agent);

CREATE INDEX IF NOT EXISTS ix_provider_usage_events_success
    ON public.provider_usage_events (success);

CREATE INDEX IF NOT EXISTS ix_provider_usage_events_provider_request_id
    ON public.provider_usage_events (provider_request_id);

CREATE INDEX IF NOT EXISTS ix_provider_usage_events_created_at
    ON public.provider_usage_events (created_at);

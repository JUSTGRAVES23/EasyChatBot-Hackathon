"""
AI Service Provider Manager domain models.

Defines the business contracts for AI provider
intelligence, operational recommendations,
and provider escalations.

This module does not:

- execute providers;
- modify Runtime routing;
- send emails;
- persist data.

Responsibilities:

- represent provider profiles;
- represent provider recommendations;
- represent provider escalations;
- represent recommendation and escalation lifecycles.

Architecture:

AI Runtime Intelligence
        |
        v
Provider Management Models
        |
        +----------------------+
        |                      |
        v                      v
Recommendations          Escalations
        |                      |
        +----------+-----------+
                   |
                   v
          Operations / Human
              Approval
"""


from __future__ import annotations


from dataclasses import dataclass
from datetime import datetime, timezone
from enum import Enum


class RecommendationStatus(
    str,
    Enum,
):
    """
    Lifecycle of provider recommendations.
    """

    GENERATED = "generated"

    REVIEW_REQUIRED = "review_required"

    APPROVED = "approved"

    REJECTED = "rejected"


class EscalationSeverity(
    str,
    Enum,
):
    """
    Escalation importance level.
    """

    LOW = "low"

    MEDIUM = "medium"

    HIGH = "high"

    CRITICAL = "critical"


class EscalationType(
    str,
    Enum,
):
    """
    Operational escalation categories.
    """

    COST_SPIKE = "cost_spike"

    QUALITY_DROP = "quality_drop"

    PROVIDER_FAILURE = "provider_failure"

    LATENCY_DEGRADATION = (
        "latency_degradation"
    )


class EscalationStatus(
    str,
    Enum,
):
    """
    Lifecycle of a provider escalation.

    Escalations are operational records and
    therefore require an explicit lifecycle
    rather than a simple boolean state.
    """

    OPEN = "open"

    ACKNOWLEDGED = "acknowledged"

    RESOLVED = "resolved"

    DISMISSED = "dismissed"


@dataclass(frozen=True)
class ProviderCapabilityProfile:
    """
    Provider capability information.

    Example:

    OpenAI:
        conversation
        reasoning
    """

    provider: str

    model: str

    capabilities: tuple[str, ...]

    priority_strategy: str


@dataclass(frozen=True)
class ProviderRecommendation:
    """
    Recommendation generated by provider intelligence.

    Recommendations are advisory.

    They require human or policy approval
    before any operational change occurs.
    """

    capability: str

    current_provider: str

    current_model: str

    recommended_provider: str

    recommended_model: str

    reason: str

    confidence: float

    status: RecommendationStatus = (
        RecommendationStatus.GENERATED
    )


@dataclass(frozen=True)
class ProviderEscalation:
    """
    Operational provider escalation record.

    Represents an issue or operational condition
    requiring human attention.

    The escalation itself does not perform
    any operational action.
    """

    escalation_id: str

    escalation_type: EscalationType

    severity: EscalationSeverity

    provider: str

    capability: str

    message: str

    recommendation: str | None = None

    created_at: datetime = (
        datetime.now(timezone.utc)
    )

    status: EscalationStatus = (
        EscalationStatus.OPEN
    )
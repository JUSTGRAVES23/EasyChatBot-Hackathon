-- P1.6.2B Provider Usage Ledger
-- Academy-owned database migration handoff.
--
-- DO NOT execute from EasyChatBot.
-- DO NOT run EasyChatBot Alembic for this migration.
--
-- Required canonical durable usage fields:
-- provider, model, capability, functionality, agent
-- input_tokens, output_tokens, total_tokens
-- latency_ms, estimated_cost, quality_score, success
-- provider_request_id, created_at

CREATE TABLE provider_usage_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    provider VARCHAR(64) NOT NULL,
    model VARCHAR(128) NOT NULL,
    capability VARCHAR(128) NOT NULL,
    functionality VARCHAR(128) NOT NULL,
    agent VARCHAR(128) NOT NULL,

    input_tokens INTEGER NULL,
    output_tokens INTEGER NULL,
    total_tokens INTEGER NULL,

    latency_ms INTEGER NULL,

    estimated_cost NUMERIC(18, 8) NOT NULL,
    quality_score NUMERIC(5, 2) NOT NULL,
    success BOOLEAN NOT NULL,

    provider_request_id VARCHAR(256) NULL,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_provider_usage_events_provider
    ON provider_usage_events (provider);

CREATE INDEX ix_provider_usage_events_model
    ON provider_usage_events (model);

CREATE INDEX ix_provider_usage_events_capability
    ON provider_usage_events (capability);

CREATE INDEX ix_provider_usage_events_functionality
    ON provider_usage_events (functionality);

CREATE INDEX ix_provider_usage_events_agent
    ON provider_usage_events (agent);

CREATE INDEX ix_provider_usage_events_success
    ON provider_usage_events (success);

CREATE INDEX ix_provider_usage_events_provider_request_id
    ON provider_usage_events (provider_request_id);

CREATE INDEX ix_provider_usage_events_created_at
    ON provider_usage_events (created_at);

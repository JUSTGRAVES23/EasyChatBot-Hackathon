"""
Runtime Execution Context.

Provides immutable runtime context shared with agents.

Responsibilities:
- identify an execution
- carry user request information
- provide runtime metadata
- optionally carry live intelligence context

Does not:
- execute providers
- manage memory
- modify systems
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any
from uuid import uuid4


@dataclass(frozen=True)
class ExecutionContext:
    """
    Runtime execution context shared with agents.

    Attributes
    ----------
    user_id:
        Identifier of the user initiating the execution.

    request:
        User request being processed.

    execution_id:
        Unique identifier for this execution.

    created_at:
        UTC timestamp when the context was created.

    metadata:
        Runtime metadata.

    intelligence_context:
        Optional provider-independent live intelligence
        generated by the Research Agent.

    Responsibilities:
    - identify an execution
    - carry user request information
    - provide runtime metadata
    - optionally carry live intelligence context

    Does not:
    - execute providers
    - manage memory
    - modify systems
    """

    user_id: str

    request: str

    execution_id: str = field(
        default_factory=lambda: str(uuid4())
    )

    created_at: datetime = field(
        default_factory=lambda: datetime.now(timezone.utc)
    )

    metadata: dict[str, Any] = field(
        default_factory=dict
    )

    intelligence_context: Any | None = None

    @property
    def has_intelligence_context(self) -> bool:
        """
        Return whether live intelligence is attached
        to this execution.
        """

        return self.intelligence_context is not None
"""
EasyChatBot AI Operations Center provider health service.

Transforms provider health observations into the current
provider health state and significant health transitions.

Architecture:

Provider Health Probe
        |
        v
ProviderHealthObservation
        |
        v
ProviderHealthService
        |
        +--------------------+
        |                    |
        v                    v
ProviderHealthState   HealthTransitionEvent
        |                    |
        +---------+----------+
                  |
                  v
        ProviderIncidentService
                  |
                  v
           EscalationService


Responsibilities:

- process provider health observations;
- maintain provider health state;
- track consecutive failures;
- track consecutive successes;
- detect degradation;
- detect unavailability;
- detect recovery;
- expose the current provider health state.

Does NOT:

- execute health probes;
- persist incidents;
- send emails;
- modify Runtime routing;
- perform autonomous failover.

The service is an application-layer health state
processor. Incident persistence and escalation remain
separate responsibilities.
"""

from __future__ import annotations

from dataclasses import replace

from app.application.provider_management.provider_health_models import (
    ProviderHealthObservation,
    ProviderHealthState,
    ProviderHealthStatus,
    ProviderHealthTransition,
    ProviderHealthTransitionEvent,
)


class ProviderHealthService:
    """
    Application service responsible for provider health
    state tracking.

    Health policy for the Hackathon:

    1. First failure:
       DEGRADED

    2. Three consecutive failures:
       UNAVAILABLE

    3. Successful observation after degradation:
       HEALTHY

    4. Successful observation after unavailability:
       HEALTHY / RECOVERED transition

    The thresholds are intentionally kept in the service
    for the Hackathon and can later become validated
    configuration.
    """

    DEGRADED_FAILURE_THRESHOLD = 1

    UNAVAILABLE_FAILURE_THRESHOLD = 3

    RECOVERY_SUCCESS_THRESHOLD = 2

    def __init__(self) -> None:
        """
        Initialise an empty provider health registry.
        """

        self._states: dict[
            str,
            ProviderHealthState,
        ] = {}

    def observe(
        self,
        observation: ProviderHealthObservation,
    ) -> ProviderHealthTransitionEvent:
        """
        Process one provider health observation.

        Returns the health transition generated by the
        observation.

        The method updates only application-level health
        state. It does not create incidents or external
        side effects.
        """

        if observation is None:
            raise ValueError(
                "Provider health observation cannot be None."
            )

        self._validate_observation(
            observation
        )

        previous_state = self._states.get(
            observation.provider
        )

        next_state = self._calculate_next_state(
            observation=observation,
            previous_state=previous_state,
        )

        self._states[
            observation.provider
        ] = next_state

        transition = (
            self._determine_transition(
                previous_state=previous_state,
                current_state=next_state,
            )
        )

        return ProviderHealthTransitionEvent(
            provider=observation.provider,
            transition=transition,
            previous_status=(
                previous_state.status
                if previous_state is not None
                else ProviderHealthStatus.UNKNOWN
            ),
            current_status=next_state.status,
            occurred_at=observation.observed_at,
            consecutive_failures=(
                next_state.consecutive_failures
            ),
            consecutive_successes=(
                next_state.consecutive_successes
            ),
            affected_capabilities=(
                (observation.capability,)
                if observation.capability
                else ()
            ),
        )

    def get_state(
        self,
        provider: str,
    ) -> ProviderHealthState | None:
        """
        Return the current state of a provider.

        Returns None when the provider has not yet been
        observed.
        """

        if not provider.strip():
            raise ValueError(
                "Provider cannot be empty."
            )

        return self._states.get(
            provider
        )

    def get_all_states(
        self,
    ) -> tuple[ProviderHealthState, ...]:
        """
        Return current health states for all observed
        providers.
        """

        return tuple(
            self._states[
                provider
            ]
            for provider in sorted(
                self._states
            )
        )

    def clear(
        self,
    ) -> None:
        """
        Clear tracked health state.

        Intended primarily for tests and isolated
        demonstrations.
        """

        self._states.clear()

    def _calculate_next_state(
        self,
        *,
        observation: ProviderHealthObservation,
        previous_state: ProviderHealthState | None,
    ) -> ProviderHealthState:
        """
        Calculate the next provider health state.
        """

        if observation.status == (
            ProviderHealthStatus.UNAVAILABLE
        ):
            consecutive_failures = (
                observation.consecutive_failures
                if observation.consecutive_failures > 0
                else (
                    (
                        previous_state.consecutive_failures
                        if previous_state is not None
                        else 0
                    )
                    + 1
                )
            )

            return ProviderHealthState(
                provider=observation.provider,
                status=(
                    ProviderHealthStatus.UNAVAILABLE
                    if consecutive_failures
                    >= self.UNAVAILABLE_FAILURE_THRESHOLD
                    else ProviderHealthStatus.DEGRADED
                ),
                checked_at=observation.observed_at,
                consecutive_failures=(
                    consecutive_failures
                ),
                consecutive_successes=0,
                last_success_at=(
                    previous_state.last_success_at
                    if previous_state is not None
                    else None
                ),
                last_failure_at=(
                    observation.observed_at
                ),
                degraded_since=(
                    previous_state.degraded_since
                    if (
                        previous_state is not None
                        and previous_state.degraded_since
                        is not None
                    )
                    else observation.observed_at
                ),
                unavailable_since=(
                    (
                        previous_state.unavailable_since
                        if previous_state is not None
                        and previous_state.unavailable_since
                        is not None
                        else observation.observed_at
                    )
                    if consecutive_failures
                    >= self.UNAVAILABLE_FAILURE_THRESHOLD
                    else None
                ),
            )

        if observation.status == (
            ProviderHealthStatus.DEGRADED
        ):
            consecutive_failures = (
                observation.consecutive_failures
                if observation.consecutive_failures > 0
                else (
                    (
                        previous_state.consecutive_failures
                        if previous_state is not None
                        else 0
                    )
                    + 1
                )
            )

            return ProviderHealthState(
                provider=observation.provider,
                status=(
                    ProviderHealthStatus.UNAVAILABLE
                    if consecutive_failures
                    >= self.UNAVAILABLE_FAILURE_THRESHOLD
                    else ProviderHealthStatus.DEGRADED
                ),
                checked_at=observation.observed_at,
                consecutive_failures=(
                    consecutive_failures
                ),
                consecutive_successes=0,
                last_success_at=(
                    previous_state.last_success_at
                    if previous_state is not None
                    else None
                ),
                last_failure_at=(
                    observation.observed_at
                ),
                degraded_since=(
                    previous_state.degraded_since
                    if (
                        previous_state is not None
                        and previous_state.degraded_since
                        is not None
                    )
                    else observation.observed_at
                ),
                unavailable_since=(
                    (
                        previous_state.unavailable_since
                        if previous_state is not None
                        and previous_state.unavailable_since
                        is not None
                        else observation.observed_at
                    )
                    if consecutive_failures
                    >= self.UNAVAILABLE_FAILURE_THRESHOLD
                    else None
                ),
            )

        if observation.status == (
            ProviderHealthStatus.HEALTHY
        ):
            consecutive_successes = (
                observation.consecutive_successes
                if observation.consecutive_successes > 0
                else (
                    (
                        previous_state.consecutive_successes
                        if previous_state is not None
                        else 0
                    )
                    + 1
                )
            )

            return ProviderHealthState(
                provider=observation.provider,
                status=ProviderHealthStatus.HEALTHY,
                checked_at=observation.observed_at,
                consecutive_failures=0,
                consecutive_successes=(
                    consecutive_successes
                ),
                last_success_at=(
                    observation.observed_at
                ),
                last_failure_at=(
                    previous_state.last_failure_at
                    if previous_state is not None
                    else None
                ),
                degraded_since=None,
                unavailable_since=None,
            )

        return ProviderHealthState(
            provider=observation.provider,
            status=ProviderHealthStatus.UNKNOWN,
            checked_at=observation.observed_at,
            consecutive_failures=(
                previous_state.consecutive_failures
                if previous_state is not None
                else 0
            ),
            consecutive_successes=(
                previous_state.consecutive_successes
                if previous_state is not None
                else 0
            ),
            last_success_at=(
                previous_state.last_success_at
                if previous_state is not None
                else None
            ),
            last_failure_at=(
                previous_state.last_failure_at
                if previous_state is not None
                else None
            ),
            degraded_since=(
                previous_state.degraded_since
                if previous_state is not None
                else None
            ),
            unavailable_since=(
                previous_state.unavailable_since
                if previous_state is not None
                else None
            ),
        )

    @staticmethod
    def _determine_transition(
        *,
        previous_state: ProviderHealthState | None,
        current_state: ProviderHealthState,
    ) -> ProviderHealthTransition:
        """
        Determine the significant transition represented
        by the latest observation.
        """

        previous_status = (
            previous_state.status
            if previous_state is not None
            else ProviderHealthStatus.UNKNOWN
        )

        current_status = current_state.status

        if (
            previous_status
            == ProviderHealthStatus.UNAVAILABLE
            and current_status
            == ProviderHealthStatus.HEALTHY
        ):
            return ProviderHealthTransition.RECOVERED

        if (
            current_status
            == ProviderHealthStatus.UNAVAILABLE
        ):
            return ProviderHealthTransition.UNAVAILABLE

        if (
            current_status
            == ProviderHealthStatus.DEGRADED
        ):
            return ProviderHealthTransition.DEGRADED

        if (
            current_status
            == ProviderHealthStatus.UNKNOWN
        ):
            return ProviderHealthTransition.UNKNOWN

        return ProviderHealthTransition.RECOVERED

    @staticmethod
    def _validate_observation(
        observation: ProviderHealthObservation,
    ) -> None:
        """
        Validate required health observation fields.
        """

        if not observation.provider.strip():
            raise ValueError(
                "Provider cannot be empty."
            )

        if observation.latency_ms is not None:
            if observation.latency_ms < 0:
                raise ValueError(
                    "Latency cannot be negative."
                )

        if observation.consecutive_failures < 0:
            raise ValueError(
                "Consecutive failures cannot be negative."
            )

        if observation.consecutive_successes < 0:
            raise ValueError(
                "Consecutive successes cannot be negative."
            )